#!/usr/bin/env python3
"""
Builds theme/seed/india-map.json, the India map on the Contact Us page (branches).

Source: Natural Earth 1:10m vector data (public domain, naturalearthdata.com):
  - ne_10m_admin_0_countries_ind.geojson: India's outline as India officially shows it
    (the "India point of view" edition), so Jammu & Kashmir and Ladakh are drawn whole.
    Maps published in India must show the official boundary.
  - ne_10m_admin_1_states_provinces.geojson: state boundaries.
Download both from https://github.com/nvkelso/natural-earth-vector (geojson/) and run:
    python3 tools/build-india-map.py ne_10m_admin_0_countries_ind.geojson ne_10m_admin_1_states_provinces.geojson
Needs shapely (pip install shapely). The output is committed, so the website needs neither.

Output: a viewBox, the outline, and for each state its outline (drawn faintly, as the
state boundaries) and a label point (Natural Earth's label position, the state's
approximate centre: a pin marks the state, never an office address).
Jammu & Kashmir and Ladakh are drawn as one region inside the official outline, without
the de facto line Natural Earth's state layer uses.
"""
import json, math, sys
from shapely.geometry import shape, mapping, MultiPolygon, Polygon
from shapely.ops import unary_union

ADM0, ADM1 = sys.argv[1], sys.argv[2]
OUT = 'theme/seed/india-map.json'
TOL = 0.06           # simplification, degrees (~6 km); plenty at the size shown
W = 1000             # viewBox width
LAT0 = 22.0          # projection: equirectangular, x scaled by cos(22°)
K = math.cos(math.radians(LAT0))

india = next(shape(f['geometry']) for f in json.load(open(ADM0))['features'] if f['properties'].get('ADM0_A3') == 'IND')
# Drop specks (rocks, sandbanks) under ~2 km2; keep Andaman & Nicobar and Lakshadweep.
india = MultiPolygon([p for p in getattr(india, 'geoms', [india]) if p.area > 0.00015])
states = {f['properties']['name']: (shape(f['geometry']).buffer(0), f['properties']) for f in json.load(open(ADM1))['features'] if f['properties'].get('adm0_a3') == 'IND'}

north = india.difference(unary_union([g for n, (g, _) in states.items() if n not in ('Jammu and Kashmir', 'Ladakh')]))
north = max(getattr(north, 'geoms', [north]), key=lambda g: g.area)  # the northern region inside the outline

minx, miny, maxx, maxy = india.bounds
S = W / ((maxx - minx) * K)
H = round((maxy - miny) * S)

def pt(x, y):
    return ((x - minx) * K * S, (maxy - y) * S)

def ring_d(coords):
    pts = [pt(x, y) for x, y in coords]
    out, last = [], None
    for x, y in pts:
        p = (round(x), round(y))
        if p != last:
            out.append(p); last = p
    if len(out) < 4:
        return ''
    return 'M' + 'L'.join('%d %d' % p for p in out) + 'Z'

def geom_d(g):
    g = g.simplify(TOL, preserve_topology=True)
    polys = getattr(g, 'geoms', [g])
    d = []
    for p in polys:
        if not isinstance(p, Polygon) or p.is_empty:
            continue
        d.append(ring_d(p.exterior.coords))
    return ''.join(d)

out_states = {}
for name, (g, props) in states.items():
    if name in ('Jammu and Kashmir', 'Ladakh'):
        continue
    g = g.intersection(india)
    lx, ly = pt(props['longitude'], props['latitude'])
    out_states[name] = {'d': geom_d(g), 'x': round(lx, 1), 'y': round(ly, 1)}
c = north.representative_point()
lx, ly = pt(c.x, c.y)
out_states['Jammu and Kashmir'] = {'d': geom_d(north), 'x': round(lx, 1), 'y': round(ly, 1), 'also': ['Ladakh']}

data = {
    '_readme': 'Generated by tools/build-india-map.py from Natural Earth (public domain). Do not edit by hand.',
    'viewBox': '0 0 %d %d' % (W, H),
    'outline': geom_d(india),
    'states': dict(sorted(out_states.items())),
}
json.dump(data, open(OUT, 'w'), separators=(',', ':'))
print(OUT, 'viewBox', data['viewBox'], 'bytes', len(json.dumps(data, separators=(',', ':'))))
